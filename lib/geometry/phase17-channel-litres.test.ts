import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { phase17ChannelBoards } from "./__fixtures__/phase17-channel-boards";
import pin from "./__fixtures__/phase17-channel-litres-pin.json";
import { bottomHasChannels } from "./bottom";
import { summarizeDesign } from "./design";

/**
 * Phase 17, plan 17-19 (gap G-17-6, the founder's ruling of 2026-11-10: "record the before/after litres per preset"):
 * the litres of the 49 channelled boards, written by scripts/extract-phase17-channel-litres-pin.ts from the app as it
 * stood before the finished rail's rule for channels changed. Today's litres must read the pin to the last digit.
 * 17-20 turns this equality into the before-and-after relations: the Hard Edge tails and any board whose channels
 * never reach the rail's curve keep these figures exactly, and the rest move by the amounts its summary records.
 * Nothing here types a figure.
 */

const PIN = pin as { provenance: string; litres: Record<string, string> };
const BOARDS = phase17ChannelBoards();

describe("the 49 channelled boards' litres, pinned before the channel rule changed (G-17-6)", () => {
  it("the set has 49 boards with unique labels, and every one carries channels", () => {
    expect(BOARDS).toHaveLength(49);
    expect(new Set(BOARDS.map((board) => board.label)).size).toBe(49);
    for (const board of BOARDS) {
      expect(bottomHasChannels(board.fields.bottom!), board.label).toBe(true);
    }
  });

  it("the pin holds exactly those boards, in order, and names its generator", () => {
    expect(Object.keys(PIN.litres)).toEqual(BOARDS.map((board) => board.label));
    expect(PIN.provenance).toContain("GENERATED by scripts/extract-phase17-channel-litres-pin.ts");
  });

  it("the generator refuses to run once volume.ts names sectionsOffAt (17-20's seam input)", () => {
    const script = readFileSync(new URL("../../scripts/extract-phase17-channel-litres-pin.ts", import.meta.url), "utf8");
    expect(script).toContain('.includes("sectionsOffAt")');
  });

  it("today's litres, board by board", () => {
    const rows = BOARDS.map((board) => `${board.label.padEnd(44)} ${summarizeDesign(board.fields).volumeLitres.toFixed(4)} L`);
    console.info(`litres today, channelled boards (G-17-6, before 17-20):\n${rows.join("\n")}`);
  });

  for (const board of BOARDS) {
    it(`${board.label}: the pinned litres to the last digit`, () => {
      expect(summarizeDesign(board.fields).volumeLitres.toPrecision(17)).toBe(PIN.litres[board.label]);
    });
  }
});
