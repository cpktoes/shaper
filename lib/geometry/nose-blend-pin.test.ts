import { describe, expect, it } from "vitest";
import {
  NOSE_BLEND_PRESET_LABELS,
  NOSE_BLEND_SWEEP_LENGTHS_IN,
  NOSE_BLEND_SWEEP_NOSES,
  noseBlendFileDigest,
  noseBlendFileLabels,
  noseBlendPinBoards,
  noseBlendSurface,
  noseBlendSurfaceDigest,
  noseBlendSurfaceLabels,
  noseBlendSweepBoards,
} from "./__fixtures__/nose-blend-boards";
import pin from "./__fixtures__/nose-blend-pin.json";
import type { BoardSurface } from "./board-surface";
import { summarizeDesign } from "./design";
import { railCharacterDifferences } from "./volume";

/**
 * Quick 261127-kkw, D-02: a board that has never moved the nose rail's two blend sliders is cut exactly as it
 * was before they existed. The record (`nose-blend-pin.json`, written once by scripts/extract-nose-blend-pin.ts
 * from the app before the sliders) holds 142 boards' litres to every digit a double carries, 44 boards' whole 3D
 * shape and 12 boards' .brd files as digests. Every one must be reproduced: to the last digit and the last byte.
 * Nothing here types a figure, and the record is never written again.
 */

const PIN = pin as {
  provenance: string;
  litres: Record<string, string>;
  surfaces: Record<string, string>;
  files: Record<string, string>;
};
const BOARDS = noseBlendPinBoards();
const SWEEP = noseBlendSweepBoards();
const SURFACE_LABELS = noseBlendSurfaceLabels();
const FILE_LABELS = noseBlendFileLabels();
/** A 3D board takes a second or two to build, longer on a loaded machine. */
const SLOW = 120_000;

const fieldsOf = (label: string) => {
  const board = BOARDS.find((b) => b.label === label);
  if (!board) throw new Error(`no board ${label}`);
  return board.fields;
};

/** Each surface is built once and shared by its shape case and its board-file case. */
const built = new Map<string, BoardSurface>();
function surfaceOf(label: string): BoardSurface {
  let surface = built.get(label);
  if (!surface) {
    surface = noseBlendSurface(fieldsOf(label));
    built.set(label, surface);
  }
  return surface;
}

describe("the record taken before the nose rail's blend had sliders (quick 261127-kkw, D-02)", () => {
  it("names its generator and holds exactly the boards the set builds: 142 litres, 44 shapes, 12 files", () => {
    expect(PIN.provenance).toContain("GENERATED by scripts/extract-nose-blend-pin.ts");
    expect(BOARDS).toHaveLength(142);
    expect(SWEEP).toHaveLength(NOSE_BLEND_SWEEP_LENGTHS_IN.length * Object.keys(NOSE_BLEND_SWEEP_NOSES).length);
    expect(SWEEP).toHaveLength(40);
    expect(new Set(BOARDS.map((board) => board.label)).size).toBe(BOARDS.length);
    expect(Object.keys(PIN.litres)).toEqual(BOARDS.map((board) => board.label));
    expect(SURFACE_LABELS).toHaveLength(44);
    expect(Object.keys(PIN.surfaces)).toEqual(SURFACE_LABELS);
    expect(FILE_LABELS).toHaveLength(12);
    expect(Object.keys(PIN.files)).toEqual(FILE_LABELS);
    for (const label of NOSE_BLEND_PRESET_LABELS) expect(BOARDS.some((board) => board.label === label)).toBe(true);
  });

  it("no board of the set says anything about the nose's blend", () => {
    for (const board of BOARDS) {
      expect(Object.keys(board.fields.rails).filter((key) => /^noseRail/.test(key))).toEqual([]);
      expect(JSON.stringify(board.fields.rails)).not.toContain("noseRail");
    }
  });

  it("every sweep board's nose rail differs from its centre's, so the nose's blend is at work on each", () => {
    for (const board of SWEEP) {
      expect(railCharacterDifferences(board.fields.rails, "nose"), board.label).not.toEqual([]);
    }
  });

  describe("litres, to the last digit", () => {
    for (const board of BOARDS) {
      it(`${board.label}`, () => {
        expect(summarizeDesign(board.fields).volumeLitres.toPrecision(17)).toBe(PIN.litres[board.label]);
      });
    }
  });

  describe("the 3D board, every vertex, triangle and face", () => {
    for (const label of SURFACE_LABELS) {
      it(
        `${label}`,
        () => {
          expect(noseBlendSurfaceDigest(surfaceOf(label))).toBe(PIN.surfaces[label]);
        },
        SLOW,
      );
    }
  });

  describe("the .brd file, every byte", () => {
    for (const label of FILE_LABELS) {
      it(
        `${label}`,
        () => {
          expect(noseBlendFileDigest(surfaceOf(label))).toBe(PIN.files[label]);
        },
        SLOW,
      );
    }
  });
});
