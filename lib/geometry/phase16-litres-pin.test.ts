import { describe, expect, it } from "vitest";
import { phase16Boards } from "./__fixtures__/phase16-boards";
import pin from "./__fixtures__/phase16-litres-pin.json";
import {
  designCrossSectionInput,
  designSideProfile,
  deriveEffectiveRails,
  LIVE_DESIGN_RULES,
  summarizeDesignWith,
  type DesignSummaryFields,
} from "./design";
import { buildOutline } from "./outline";
import { boardSections, computeCrossSectionVolume, crossSectionStations, HARD_EDGE_SWITCH } from "./volume";
import { mm } from "./units";

/**
 * Phase 16, D-05 (research Pattern 1): the litres and the 3D board read ONE section function. The pin
 * (`phase16-litres-pin.json`, written by scripts/extract-phase16-litres-pin.ts from the code as it stood
 * before `boardSections` existed) records forty boards' litres to every digit; under the pre-Phase-16
 * hard-edge rule, named, the refactored litres must reproduce every one bit for bit. Nothing here types a
 * figure.
 */

const PIN = pin as { provenance: string; litres: Record<string, string> };

/** The cross-section input `summarizeDesignWith` builds for a board, built the same way. */
function crossSectionInputOf(fields: DesignSummaryFields) {
  const geometry = buildOutline(fields.outline);
  const profile = designSideProfile(fields, LIVE_DESIGN_RULES);
  const rails = deriveEffectiveRails(fields.rails, profile.effectiveFoil, fields.railsImportFoilThickness);
  return designCrossSectionInput(geometry, profile, rails, fields.outline.length);
}

const BOARDS = phase16Boards();

describe("the forty boards' litres, pinned before boardSections (D-05)", () => {
  it("the pin holds the forty boards the set builds, and names its generator", () => {
    expect(Object.keys(PIN.litres)).toEqual(BOARDS.map((board) => board.label));
    expect(BOARDS).toHaveLength(40);
    expect(PIN.provenance).toContain("GENERATED by scripts/extract-phase16-litres-pin.ts");
  });

  for (const board of BOARDS) {
    it(`${board.label}: the old switch reproduces the pinned litres to the last digit`, () => {
      const litres = summarizeDesignWith(board.fields, { ...LIVE_DESIGN_RULES, hardEdge: HARD_EDGE_SWITCH }).volumeLitres;
      expect(litres.toPrecision(17)).toBe(PIN.litres[board.label]);
    });
  }
});

describe("the litres integrate exactly the sections boardSections returns (D-05)", () => {
  for (const board of BOARDS) {
    it(`${board.label}: station for station, area for area`, () => {
      const input = crossSectionInputOf(board.fields);
      const sections = boardSections(input);
      const volume = computeCrossSectionVolume(input);
      expect(sections.map((section) => section.station)).toEqual(
        crossSectionStations(input.length, input.cutStation ?? mm(0)),
      );
      expect(volume.stations).toEqual(sections.map((section) => section.station));
      expect(sections).toHaveLength(volume.stationAreas.length);
      sections.forEach((section, i) => {
        expect(Object.is(section.area, volume.stationAreas[i]), `area at station ${i}`).toBe(true);
        expect(Object.is(section.blendArea, volume.stationBlendAreas[i]), `blend at station ${i}`).toBe(true);
      });
    });
  }
});
