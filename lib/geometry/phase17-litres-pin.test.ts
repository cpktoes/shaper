import { describe, expect, it } from "vitest";
import { phase16SurfaceBoards } from "./__fixtures__/phase16-boards";
import pin from "./__fixtures__/phase17-litres-pin.json";
import { summarizeDesign } from "./design";

/**
 * Phase 17, D-20 (SPEC edge "The litres pin (flat)", first half): the litres of the 102 Phase 16 boards, written
 * by scripts/extract-phase17-litres-pin.ts from the app as it stood before the bottom contours could take any foam
 * off. Every one of these boards has a flat bottom, so the live litres must read the pin to the last digit — now,
 * and after the bottom joins the litres. Nothing here types a figure.
 */

const PIN = pin as { provenance: string; litres: Record<string, string> };
const BOARDS = phase16SurfaceBoards();

describe("the 102 boards' litres, pinned before the bottom seam (D-20)", () => {
  it("the pin holds the 102 boards the set builds, in order, and names its generator", () => {
    expect(BOARDS).toHaveLength(102);
    expect(Object.keys(PIN.litres)).toEqual(BOARDS.map((board) => board.label));
    expect(PIN.provenance).toContain("GENERATED by scripts/extract-phase17-litres-pin.ts");
  });

  for (const board of BOARDS) {
    it(`${board.label}: the live litres reproduce the pinned figure to the last digit`, () => {
      expect(summarizeDesign(board.fields).volumeLitres.toPrecision(17)).toBe(PIN.litres[board.label]);
    });
  }
});
