import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { phase16SurfaceBoards } from "./__fixtures__/phase16-boards";
import pin from "./__fixtures__/phase17-litres-pin.json";
import { BOTTOM_SECTIONS, bottomHasChannels, bottomHasCut, DEFAULT_BOTTOM, type BoardBottom } from "./bottom";
import { HALF_SECTION_POINT_COUNT } from "./finished-rail";
import {
  designCrossSectionInput,
  designSideProfile,
  deriveEffectiveRails,
  LIVE_DESIGN_RULES,
  summarizeDesign,
  type DesignSummaryFields,
} from "./design";
import { buildOutline } from "./outline";
import { inchesToMm, mm } from "./units";
import { boardSections, computeCrossSectionVolume, halfSectionPointCount } from "./volume";

/**
 * Phase 17, D-20 (SPEC edge "The litres pin (flat)" and the prohibition "A flat bottom must NOT change any litres
 * figure"): the litres of the 102 Phase 16 boards, written by scripts/extract-phase17-litres-pin.ts from the app as it
 * stood before the bottom contours could take any foam off. Every one of these boards has a flat bottom, so the live
 * litres must read the pin to the last digit — with no bottom at all, with the default bottom, and with a bottom whose
 * three sections are flat but carry other numbers and whose channels are off — and the seam itself, run with nothing to
 * take off, must leave every station's area exactly what it was. Nothing here types a figure.
 */

const PIN = pin as { provenance: string; litres: Record<string, string> };
const BOARDS = phase16SurfaceBoards();

/** Three flat sections carrying numbers no flat is stored with, and channels with a count of 0 but other numbers. */
const FLAT_BUT_NOT_DEFAULT: BoardBottom = {
  ...structuredClone(DEFAULT_BOTTOM),
  ...Object.fromEntries(
    BOTTOM_SECTIONS.map((section) => [
      section,
      {
        ...DEFAULT_BOTTOM[section],
        offRail: inchesToMm(2),
        offStringer: inchesToMm(1),
        start: inchesToMm(30),
        deepest: inchesToMm(20),
        end: inchesToMm(4),
        depth: inchesToMm(1 / 4),
        smoothness: 70,
      },
    ]),
  ),
  channels: { ...DEFAULT_BOTTOM.channels, count: 0, depth: inchesToMm(1 / 2), width: inchesToMm(2) },
  wingRule: "natural",
};

/** The cross-section input `summarizeDesign` builds for a board, built the same way. */
function crossSectionInputOf(fields: DesignSummaryFields) {
  const geometry = buildOutline(fields.outline);
  const profile = designSideProfile(fields, LIVE_DESIGN_RULES);
  const rails = deriveEffectiveRails(fields.rails, profile.effectiveFoil, fields.railsImportFoilThickness);
  return designCrossSectionInput(geometry, profile, rails, fields.outline.length);
}

describe("the 102 boards' litres, pinned before the bottom seam (D-20)", () => {
  it("the pin holds the 102 boards the set builds, in order, and names its generator", () => {
    expect(BOARDS).toHaveLength(102);
    expect(Object.keys(PIN.litres)).toEqual(BOARDS.map((board) => board.label));
    expect(PIN.provenance).toContain("GENERATED by scripts/extract-phase17-litres-pin.ts");
  });

  it("the generator now refuses to run: the code it pinned has the bottom's seam in it", () => {
    const volume = readFileSync(new URL("./volume.ts", import.meta.url), "utf8");
    const script = readFileSync(new URL("../../scripts/extract-phase17-litres-pin.ts", import.meta.url), "utf8");
    expect(volume).toContain("foamOffAt");
    expect(script).toContain('.includes("foamOffAt")');
  });

  it("a flat bottom with other numbers cuts nothing, so it is never handed to the litres", () => {
    expect(bottomHasCut(DEFAULT_BOTTOM)).toBe(false);
    expect(bottomHasCut(FLAT_BUT_NOT_DEFAULT)).toBe(false);
  });

  it("17-06: channels set to None carry no walls, so every one of these boards keeps its rings at their usual length (research Pitfall 7)", () => {
    expect(bottomHasChannels(DEFAULT_BOTTOM)).toBe(false);
    expect(bottomHasChannels(FLAT_BUT_NOT_DEFAULT)).toBe(false);
    for (const board of BOARDS) {
      const input = crossSectionInputOf(board.fields);
      expect("bottomWallsAt" in input).toBe(false);
      expect(halfSectionPointCount(input)).toBe(HALF_SECTION_POINT_COUNT);
    }
  });

  for (const board of BOARDS) {
    it(`${board.label}: the pinned litres to the last digit with no bottom, the default bottom and a flat one with other numbers`, () => {
      const expected = PIN.litres[board.label];
      expect(summarizeDesign(board.fields).volumeLitres.toPrecision(17)).toBe(expected);
      expect(summarizeDesign({ ...board.fields, bottom: DEFAULT_BOTTOM }).volumeLitres.toPrecision(17)).toBe(expected);
      expect(summarizeDesign({ ...board.fields, bottom: FLAT_BUT_NOT_DEFAULT }).volumeLitres.toPrecision(17)).toBe(expected);
    });
  }
});

describe("the seam run with nothing to take off leaves every station's area exactly as it was (D-20, D-21)", () => {
  for (const board of BOARDS) {
    it(`${board.label}: station for station, Object.is, and the pinned litres`, () => {
      const input = crossSectionInputOf(board.fields);
      expect(input.foamOffAt).toBeUndefined();
      const forced = { ...input, foamOffAt: () => mm(0) };
      const plain = boardSections(input);
      const seamed = boardSections(forced);
      expect(seamed).toHaveLength(plain.length);
      seamed.forEach((section, i) => {
        expect(Object.is(section.area, plain[i].area), `area at station ${i}`).toBe(true);
        expect(section.drawn).toEqual(plain[i].drawn);
        expect(section.thinAt).toBeUndefined();
        expect(section.railEdgeAt).toBeUndefined();
      });
      expect(computeCrossSectionVolume(forced).volumeLitres.toPrecision(17)).toBe(PIN.litres[board.label]);
    });
  }
});
