import { describe, expect, it } from "vitest";
import { phase16FinCases } from "./__fixtures__/phase16-fin-cases";
import pin from "./__fixtures__/phase16-fin-pin.json";
import { FIN_QUAD_REAR_OF_FRONT, finTemplateFootprint, placedFins } from "./fin-outline";
import { defaultForwardBaseLength } from "./fins";
import { inchesToMm } from "./units";

/**
 * Phase 16, D-35 (plan 16-17): every preset's fins as the 3D board drew them before each took a real shape. The pin
 * (`phase16-fin-pin.json`, written by scripts/extract-phase16-fin-pin.ts from 16-10's code, before `FIN_TEMPLATES`
 * existed) is the "before" of every table in the plan's SUMMARY. Every fin has to stand where the pin says unless the
 * founder's rulings moved it, and then by exactly what they moved, worked out from the pin. Nothing here types a figure
 * of a fin's place.
 */

interface PinnedFin {
  markRole: string;
  side: number;
  role: string;
  base: number;
  depth: number;
  thickness: number;
  leading: number[];
  trailing: number[];
  rootZ: number;
  tiltRad: number;
  points: number;
  area: number;
  top: { u: number; v: number };
  rearmost: { u: number; v: number };
  sweepDeg: number;
}

const PIN = pin as { provenance: string; fins: Record<string, PinnedFin> };
const CASES = phase16FinCases();

describe("the fin pin (D-35)", () => {
  it("names its generator", () => {
    expect(PIN.provenance).toContain("GENERATED by scripts/extract-phase16-fin-pin.ts");
  });

  it("has 32 cases, each label unique, 4 presets by the opened board and the seven setups", () => {
    expect(CASES).toHaveLength(32);
    expect(new Set(CASES.map((c) => c.label)).size).toBe(32);
  });

  it("holds exactly the cases' fins", () => {
    const labels = CASES.flatMap((c) => c.marks.map((_, i) => `${c.label}|${i}`));
    expect(Object.keys(PIN.fins)).toEqual(labels);
  });

  for (const { label, preset, spec, marks, rockerAt } of CASES) {
    it(`${label}: every fin stands where the pin says, but for what D-35 and the twin defaults moved`, () => {
      const fins = placedFins(marks, spec.finSetup, spec.twinTemplate, preset.outline.length, rockerAt);
      expect(fins).toHaveLength(marks.length);
      const twinReset = label.split("|")[1].startsWith("twin/");
      const thrusterDepth = PIN.fins[`${preset.id}|thruster|0`].depth;
      fins.forEach((fin, i) => {
        const pinned = PIN.fins[`${label}|${i}`];
        expect(marks[i].role).toBe(pinned.markRole);
        expect(marks[i].side).toBe(pinned.side);
        expect(fin.outline.points).toHaveLength(fin.role === "twinKeel" ? 93 : 70);
        expect(pinned.points).toBe(56);

        // The depth: the pinned one where D-35 keeps it, otherwise worked out from the pin.
        if (fin.role === "quadRear" || fin.role === "trailer") {
          expect(fin.outline.depth).toBe(FIN_QUAD_REAR_OF_FRONT * thrusterDepth);
        } else if (fin.role === "sideBite") {
          expect(fin.outline.depth).toBe(inchesToMm(3.5));
        } else if (fin.role === "twoPlusOneCentre") {
          expect(Math.abs(fin.outline.depth - (pinned.depth - inchesToMm(1)))).toBeLessThan(1e-9);
        } else {
          expect(fin.outline.depth).toBe(pinned.depth);
        }

        if (fin.role === "twoPlusOneCentre") {
          // Shorter than today's centre, in the same place in its box.
          const centre = (pin: readonly number[], other: readonly number[]) => (pin[0] + other[0]) / 2;
          expect(Math.abs(centre(fin.leading, fin.trailing) - centre(pinned.leading, pinned.trailing))).toBeLessThan(1e-9);
          expect(Math.abs(fin.rootZ - pinned.rootZ)).toBeLessThan(1e-9);
          expect(Math.abs(fin.tiltRad - pinned.tiltRad)).toBeLessThan(1e-9);
          expect(Math.abs(fin.outline.base - 0.7 * fin.outline.depth)).toBeLessThan(1e-9);
          return;
        }

        if (twinReset && pinned.markRole !== "center") {
          // A twin after Reset: the pin holds FINS' old 4.5", so only the leading dot has moved, by the base's change.
          const grew = defaultForwardBaseLength(spec.finSetup, spec.twinTemplate) - pinned.base;
          if (fin.role === "twinKeel") {
            const heelAt = finTemplateFootprint("keel");
            const unit = {
              x: (fin.trailing[0] - fin.leading[0]) / fin.outline.base,
              y: (fin.trailing[1] - fin.leading[1]) / fin.outline.base,
            };
            const heel = {
              x: fin.leading[0] + unit.x * heelAt * fin.outline.base,
              y: fin.leading[1] + unit.y * heelAt * fin.outline.base,
            };
            expect(Math.hypot(heel.x - pinned.trailing[0], heel.y - pinned.trailing[1])).toBeLessThan(0.05);
            expect(Math.hypot(fin.leading[0] - (pinned.leading[0] + grew), fin.leading[1] - pinned.leading[1])).toBeLessThan(0.05);
          } else {
            expect(fin.trailing[0]).toBe(pinned.trailing[0]);
            expect(fin.trailing[1]).toBe(pinned.trailing[1]);
            expect(fin.leading[1]).toBe(pinned.leading[1]);
            expect(Math.abs(fin.leading[0] - (pinned.leading[0] + grew))).toBeLessThan(1e-9);
          }
          return;
        }

        expect([...fin.leading]).toEqual(pinned.leading);
        expect([...fin.trailing]).toEqual(pinned.trailing);
        expect(fin.rootZ).toBe(pinned.rootZ);
        expect(fin.tiltRad).toBe(pinned.tiltRad);
        expect(fin.outline.base).toBe(pinned.base);
      });
    });
  }
});
